// Custom drone groups live in the account (core_user) file under
// ui -> droneBlah2 as (timestamp, {label: {droneGroupID, droneIDs, id, label}}).
// droneIDs are the item ids of the player's own drones, so presets are written
// as empty groups the player fills by dragging drones in.
//
// Group names come from a naming pattern applied to each preset's stats. A
// stored group belongs to a preset when its name starts with the preset's
// family name or one of its drones' names, which keeps assigned drones when
// the pattern or a new catalog changes the rest of the name. Patterns must
// therefore start with {name}.

use std::collections::{HashMap, HashSet};
use std::fmt;
use std::fs;
use std::path::Path;
use std::sync::Arc;

use serde::Deserialize;
use serde_json::{Map, Value, json};

use crate::backups::auto_backup;
use crate::catalog::RemoteCatalog;
use crate::marshal::{encode_settings_json, filetime_now, load_settings_json, strip_type_prefix};

const UI_KEY: &str = "bytes:ui";
const GROUPS_KEY: &str = "bytes:droneBlah2";

// Generated by tools/drone-catalog from the SDE and the refine fitting engine.
static CATALOG: RemoteCatalog<DroneGroupPreset> = RemoteCatalog::new(
    "drone catalog",
    include_str!("../data/drone_groups.json"),
    "drone_groups.json",
    1,
    "sde_build",
    "presets",
);

// Text outside brackets is always written; a [bracketed] section is dropped
// when a token inside it has no value for the drone (sentries have no speed).
pub const DEFAULT_PATTERN: &str =
    "{name}[ | {damage}][ | {dps}][ | {effect}][ | {speed}][ | {range}]";

pub const PATTERN_STYLES: [(&str, &str); 3] = [
    ("detailed", DEFAULT_PATTERN),
    ("compact", "{name}[ {damage}][ {dps}][ {effect}]"),
    ("plain", "{name}"),
];

pub const PATTERN_TOKENS: [&str; 6] = ["name", "damage", "dps", "speed", "range", "effect"];

#[derive(Deserialize, Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[serde(rename_all = "lowercase")]
pub enum DroneCategory {
    Light,
    Medium,
    Heavy,
    Sentry,
    Special,
    Ewar,
    Logistics,
    Industry,
}

impl DroneCategory {
    pub fn id(&self) -> &'static str {
        match self {
            Self::Light => "light",
            Self::Medium => "medium",
            Self::Heavy => "heavy",
            Self::Sentry => "sentry",
            Self::Special => "special",
            Self::Ewar => "ewar",
            Self::Logistics => "logistics",
            Self::Industry => "industry",
        }
    }
}

// Max-skill numbers of the drone a preset is named after.
#[derive(Deserialize, Debug, Clone, Default, PartialEq)]
pub struct DroneStats {
    pub damage: Option<String>,
    // DPS of a full flight
    pub dps: Option<f64>,
    // m/s; absent for sentries
    pub speed: Option<f64>,
    // Meters; only for sentries
    pub optimal: Option<f64>,
    pub falloff: Option<f64>,
    // Repair, yield or EWAR strength, already formatted
    pub effect: Option<String>,
}

#[derive(Deserialize, Debug, Clone, PartialEq)]
pub struct DroneGroupPreset {
    pub id: String,
    pub name: String,
    pub category: DroneCategory,
    pub group_id: i64,
    // The drone whose icon represents the group; absent in older catalogs
    #[serde(default)]
    pub type_id: Option<i64>,
    pub members: Vec<String>,
    pub stats: DroneStats,
}

impl DroneGroupPreset {
    fn token(&self, token: &str) -> Option<String> {
        let stats = &self.stats;
        match token {
            "name" => Some(self.name.clone()),
            "damage" => stats.damage.clone(),
            "dps" => stats.dps.map(|dps| format!("{dps:.0}dps")),
            "speed" => stats.speed.map(|speed| format!("{}m/s", kilo(speed))),
            "range" => stats.optimal.map(|optimal| match stats.falloff {
                Some(falloff) => format!("{}+{}m", kilo(optimal), kilo(falloff)),
                None => format!("{}m", kilo(optimal)),
            }),
            "effect" => stats.effect.clone(),
            _ => None,
        }
    }

    // The group name under `pattern`, or under the default one when the
    // pattern is invalid.
    pub fn label(&self, pattern: &str) -> String {
        let parts = parse_pattern(pattern)
            .or_else(|_| parse_pattern(DEFAULT_PATTERN))
            .unwrap_or_default();
        let mut out = String::new();
        for part in &parts {
            match part {
                Part::Optional(inner) => {
                    if let Some(text) = self.render_all(inner) {
                        out.push_str(&text);
                    }
                }
                Part::Token(token) => out.push_str(&self.token(token).unwrap_or_default()),
                Part::Text(text) => out.push_str(text),
            }
        }
        out.trim().to_string()
    }

    fn render_all(&self, parts: &[Part]) -> Option<String> {
        parts.iter().try_fold(String::new(), |mut out, part| {
            match part {
                Part::Text(text) => out.push_str(text),
                Part::Token(token) => out.push_str(&self.token(token)?),
                Part::Optional(_) => unreachable!("sections do not nest"),
            }
            Some(out)
        })
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum PatternError {
    MustStartWithName,
    UnknownToken(String),
    Unbalanced,
}

impl fmt::Display for PatternError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MustStartWithName => write!(f, "The pattern must start with {{name}}"),
            Self::UnknownToken(token) => write!(f, "Unknown token {{{token}}}"),
            Self::Unbalanced => write!(f, "Unbalanced brackets or braces"),
        }
    }
}

enum Part {
    Text(String),
    Token(String),
    Optional(Vec<Part>),
}

fn parse_pattern(pattern: &str) -> Result<Vec<Part>, PatternError> {
    if !pattern.starts_with("{name}") {
        return Err(PatternError::MustStartWithName);
    }
    let mut parts = Vec::new();
    let mut section: Option<Vec<Part>> = None;
    let mut chars = pattern.chars();
    let mut text = String::new();

    fn flush(text: &mut String, section: &mut Option<Vec<Part>>, parts: &mut Vec<Part>) {
        if !text.is_empty() {
            let part = Part::Text(std::mem::take(text));
            section.as_mut().unwrap_or(parts).push(part);
        }
    }

    while let Some(c) = chars.next() {
        match c {
            '{' => {
                flush(&mut text, &mut section, &mut parts);
                let mut token = String::new();
                loop {
                    match chars.next() {
                        Some('}') => break,
                        Some(c) => token.push(c),
                        None => return Err(PatternError::Unbalanced),
                    }
                }
                if !PATTERN_TOKENS.contains(&token.as_str()) {
                    return Err(PatternError::UnknownToken(token));
                }
                section
                    .as_mut()
                    .unwrap_or(&mut parts)
                    .push(Part::Token(token));
            }
            '[' if section.is_none() => {
                flush(&mut text, &mut section, &mut parts);
                section = Some(Vec::new());
            }
            ']' if section.is_some() => {
                flush(&mut text, &mut section, &mut parts);
                parts.push(Part::Optional(section.take().unwrap_or_default()));
            }
            '[' | ']' | '}' => return Err(PatternError::Unbalanced),
            c => text.push(c),
        }
    }
    if section.is_some() {
        return Err(PatternError::Unbalanced);
    }
    flush(&mut text, &mut section, &mut parts);
    Ok(parts)
}

pub fn validate_pattern(pattern: &str) -> Result<(), PatternError> {
    parse_pattern(pattern).map(|_| ())
}

// 4200 -> "4.2k", 4000 -> "4k", 688 -> "688"
fn kilo(value: f64) -> String {
    if value >= 1000.0 {
        format!("{:.1}k", value / 1000.0).replace(".0k", "k")
    } else {
        format!("{value:.0}")
    }
}

// Presets in display order: by category, then size.
pub fn catalog() -> Arc<[DroneGroupPreset]> {
    CATALOG.items()
}

pub fn load_cached_catalog(data_dir: &Path) {
    CATALOG.load_cached(data_dir);
}

// CI regenerates the catalog after each SDE release that changes drones.
pub fn refresh_catalog(data_dir: &Path) -> Result<bool, String> {
    CATALOG.refresh(data_dir)
}

fn stored_groups(root: &Value) -> Option<&Map<String, Value>> {
    root.get(UI_KEY)
        .and_then(|ui| ui.get(GROUPS_KEY))
        .and_then(|v| v.get("tuple"))
        .and_then(|t| t.get(1))
        .and_then(|v| v.as_object())
}

fn group_label(key: &str, group: &Value) -> String {
    let label = group
        .get("bytes:label")
        .and_then(|v| v.as_str())
        .unwrap_or(key);
    strip_type_prefix(label).to_string()
}

fn has_drones(group: &Value) -> bool {
    group
        .get("bytes:droneIDs")
        .and_then(|ids| ids.as_array())
        .is_some_and(|ids| !ids.is_empty())
}

// The longest family or drone name the label starts with, as a whole word:
// "Hobgoblin | ..." is the Hobgoblin family, "Hobgoblin SD-300" the light
// sensor damp group.
fn matching_preset<'a>(
    presets: &'a [DroneGroupPreset],
    label: &str,
) -> Option<&'a DroneGroupPreset> {
    presets
        .iter()
        .flat_map(|preset| {
            std::iter::once(preset.name.as_str())
                .chain(preset.members.iter().map(String::as_str))
                .map(move |name| (name, preset))
        })
        .filter(|(name, _)| {
            label
                .strip_prefix(name)
                .is_some_and(|rest| rest.chars().next().is_none_or(|c| !c.is_alphanumeric()))
        })
        .max_by_key(|(name, _)| name.len())
        .map(|(_, preset)| preset)
}

fn present_in_settings(root: &Value, presets: &[DroneGroupPreset]) -> HashSet<String> {
    stored_groups(root)
        .into_iter()
        .flatten()
        .filter_map(|(key, group)| matching_preset(presets, &group_label(key, group)))
        .map(|p| p.id.clone())
        .collect()
}

fn group_entry(preset: &DroneGroupPreset, label: &str, drone_ids: Value, created: Value) -> Value {
    let label = format!("utf8:{label}");
    json!({
        "bytes:droneGroupID": preset.group_id,
        "bytes:droneIDs": drone_ids,
        "bytes:id": {"tuple": [label.clone(), created]},
        "bytes:label": label,
    })
}

fn presets_into_settings(
    root: &mut Value,
    presets: &[DroneGroupPreset],
    selected: &HashSet<String>,
    pattern: &str,
) -> Result<(), String> {
    let now = filetime_now();
    let mut groups = Map::new();
    let mut written = HashSet::new();
    let stored: Vec<(&String, &Value, Option<&DroneGroupPreset>)> = stored_groups(root)
        .into_iter()
        .flatten()
        .map(|(key, group)| {
            (
                key,
                group,
                matching_preset(presets, &group_label(key, group)),
            )
        })
        .collect();

    // A selected preset takes over one group matching it, renamed but keeping
    // its drones. The group already carrying the new name wins, so no other
    // group can end up under the same key.
    let mut owners: HashMap<&str, &String> = HashMap::new();
    for (key, group, preset) in &stored {
        let Some(preset) = preset.filter(|p| selected.contains(&p.id)) else {
            continue;
        };
        if group_label(key, group) == preset.label(pattern)
            || !owners.contains_key(preset.id.as_str())
        {
            owners.insert(&preset.id, key);
        }
    }

    // Groups that match no preset stay as they are. Any other matching group
    // is dropped only when it holds no drones, so a deselect never loses a
    // player's assignments.
    for (key, group, preset) in &stored {
        match preset {
            Some(preset) if owners.get(preset.id.as_str()) == Some(key) => {
                written.insert(preset.id.clone());
                let drone_ids = group.get("bytes:droneIDs").cloned().unwrap_or(json!([]));
                let created = group
                    .get("bytes:id")
                    .and_then(|id| id.get("tuple"))
                    .and_then(|t| t.get(1))
                    .cloned()
                    .unwrap_or_else(|| json!(format!("bytes:{now}")));
                let label = preset.label(pattern);
                groups.insert(
                    format!("utf8:{label}"),
                    group_entry(preset, &label, drone_ids, created),
                );
            }
            Some(_) if !has_drones(group) => {}
            _ => {
                groups.insert((*key).clone(), (*group).clone());
            }
        }
    }

    // Distinct creation stamps keep the client's group ids unique
    for (i, preset) in presets.iter().enumerate() {
        if selected.contains(&preset.id) && written.insert(preset.id.clone()) {
            let created = json!(format!("bytes:{}", now + i as u64));
            let label = preset.label(pattern);
            groups.insert(
                format!("utf8:{label}"),
                group_entry(preset, &label, json!([]), created),
            );
        }
    }

    root.as_object_mut()
        .ok_or("Settings file has an unexpected structure")?
        .entry(UI_KEY.to_string())
        .or_insert_with(|| json!({}))
        .as_object_mut()
        .ok_or("Settings 'ui' section has an unexpected structure")?
        .insert(
            GROUPS_KEY.to_string(),
            json!({"tuple": [format!("long:{now}"), groups]}),
        );
    Ok(())
}

// Ids of the catalog presets the account already has.
pub fn read_drone_groups(path: &Path) -> Result<HashSet<String>, String> {
    let (json, _) = load_settings_json(path)?;
    Ok(present_in_settings(&json, &catalog()))
}

pub fn write_drone_groups(
    path: &Path,
    selected: &HashSet<String>,
    pattern: &str,
    backup: bool,
) -> Result<(), String> {
    validate_pattern(pattern).map_err(|e| e.to_string())?;
    if !path.exists() {
        return Err("Settings file does not exist".into());
    }
    if backup {
        auto_backup(path, "pre-drone-groups")?;
    }

    let (mut json, had_crc) = load_settings_json(path)?;
    presets_into_settings(&mut json, &catalog(), selected, pattern)?;
    let bytes = encode_settings_json(&json, had_crc)?;
    fs::write(path, bytes).map_err(|e| format!("Failed to write settings file: {}", e))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ids(list: &[&str]) -> HashSet<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    fn preset(name: &str) -> DroneGroupPreset {
        catalog().iter().find(|p| p.name == name).unwrap().clone()
    }

    fn group(label: &str, drones: &[&str]) -> Value {
        json!({
            "bytes:droneGroupID": 100,
            "bytes:droneIDs": drones,
            "bytes:id": {"tuple": [format!("utf8:{label}"), "bytes:7"]},
            "bytes:label": format!("utf8:{label}"),
        })
    }

    #[test]
    fn catalog_is_bundled() {
        let catalog = catalog();
        assert!(catalog.len() > 30);
        let mut seen = HashSet::new();
        assert!(catalog.iter().all(|p| seen.insert(&p.id)));
        assert!(catalog.iter().all(|p| p.members.contains(&p.name)
            || p.members.contains(&format!("{} II", p.name))
            || p.category == DroneCategory::Ewar));
    }

    #[test]
    fn fetched_catalogs_are_checked() {
        assert!(CATALOG.parse(CATALOG.bundled).is_ok());
        let mut file: Value = serde_json::from_str(CATALOG.bundled).unwrap();
        file["schema"] = json!(CATALOG.schema + 1);
        assert!(CATALOG.parse(&file.to_string()).is_err());
        file["schema"] = json!(CATALOG.schema);
        file["presets"] = json!([]);
        assert!(CATALOG.parse(&file.to_string()).is_err());
        assert!(CATALOG.parse("<html>").is_err());
    }

    #[test]
    fn patterns_render_and_drop_missing_sections() {
        let hobgoblin = preset("Hobgoblin");
        let label = hobgoblin.label(DEFAULT_PATTERN);
        assert!(label.starts_with("Hobgoblin | Therm | "), "{label}");
        assert!(label.ends_with("km/s"), "{label}");

        // Sentries have range instead of speed
        assert!(preset("Garde").label(DEFAULT_PATTERN).ends_with("km"));
        assert!(!preset("Garde").label(DEFAULT_PATTERN).contains("m/s"));
        assert_eq!(
            preset("Light ECM").label(DEFAULT_PATTERN),
            "Light ECM | 1 jam | 4km/s"
        );
        assert_eq!(preset("Light ECM").label("{name}[ {dps}]"), "Light ECM");

        assert_eq!(hobgoblin.label("{name}"), "Hobgoblin");
        assert_eq!(hobgoblin.label("{name} ({damage})"), "Hobgoblin (Therm)");
        // Outside brackets a missing value renders empty
        assert_eq!(preset("Light ECM").label("{name} {damage}"), "Light ECM");
    }

    #[test]
    fn invalid_patterns_are_rejected() {
        assert_eq!(validate_pattern(DEFAULT_PATTERN), Ok(()));
        assert_eq!(
            validate_pattern("{dps} {name}"),
            Err(PatternError::MustStartWithName)
        );
        assert_eq!(
            validate_pattern("{name} {tank}"),
            Err(PatternError::UnknownToken("tank".into()))
        );
        assert_eq!(
            validate_pattern("{name}[ {dps}"),
            Err(PatternError::Unbalanced)
        );
        assert_eq!(
            validate_pattern("{name}[[{dps}]]"),
            Err(PatternError::Unbalanced)
        );
        assert_eq!(
            validate_pattern("{name} {dps"),
            Err(PatternError::Unbalanced)
        );
        // Invalid patterns fall back to the default when rendering
        assert_eq!(
            preset("Ogre").label("{dps}"),
            preset("Ogre").label(DEFAULT_PATTERN)
        );
    }

    #[test]
    fn groups_match_by_longest_name() {
        let catalog = catalog();
        let id = |label: &str| matching_preset(&catalog, label).map(|p| p.id.as_str());
        assert_eq!(id("Hobgoblin | Therm | 99dps"), Some("hobgoblin"));
        assert_eq!(id("Hobgoblin"), Some("hobgoblin"));
        assert_eq!(id("Federation Navy Hobgoblin"), Some("hobgoblin"));
        assert_eq!(id("Hobgoblin SD-300"), Some("light-sensor-damp"));
        assert_eq!(id("Hobgoblins"), None);
        assert_eq!(id("EC-300"), None);
    }

    #[test]
    fn drone_groups_round_trip_through_marshal() {
        let dir = std::env::temp_dir().join("eve-wrench-drone-group-test");
        fs::create_dir_all(&dir).unwrap();
        let path = dir.join("core_user_12345.dat");

        let initial = json!({
            "bytes:ui": {
                "bytes:missilesEnabled": {"tuple": ["long:134280801871504062", true]},
                "bytes:droneBlah2": {"tuple": ["long:134368794607000063", {
                    "utf8:My drones": group("My drones", &["long:1"]),
                    "utf8:Hobgoblin | Therm | 1dps": group("Hobgoblin | Therm | 1dps", &["long:42"]),
                    "utf8:Wasp II": group("Wasp II", &["long:43"]),
                    "utf8:Ogre": group("Ogre", &[]),
                }]},
            }
        });
        fs::write(&path, encode_settings_json(&initial, false).unwrap()).unwrap();

        assert_eq!(
            read_drone_groups(&path).unwrap(),
            ids(&["hobgoblin", "wasp", "ogre"])
        );

        // Hobgoblin renamed keeping its drones, ECM added, the empty Ogre
        // group dropped, Wasp II kept because it holds drones
        write_drone_groups(&path, &ids(&["hobgoblin", "light-ecm"]), "{name}", false).unwrap();
        let (json, _) = load_settings_json(&path).unwrap();
        assert_eq!(
            json[UI_KEY]["bytes:missilesEnabled"]["tuple"][1],
            json!(true)
        );
        let groups = stored_groups(&json).unwrap();
        let mut names: Vec<&str> = groups.keys().map(|k| strip_type_prefix(k)).collect();
        names.sort();
        assert_eq!(names, ["Hobgoblin", "Light ECM", "My drones", "Wasp II"]);
        assert_eq!(
            groups["utf8:Hobgoblin"]["bytes:droneIDs"],
            json!(["long:42"])
        );
        assert_eq!(
            groups["utf8:Hobgoblin"]["bytes:id"]["tuple"][1],
            json!("bytes:7")
        );
        assert_eq!(groups["utf8:Light ECM"]["bytes:droneIDs"], json!([]));
        assert_eq!(
            groups["utf8:Light ECM"]["bytes:droneGroupID"],
            json!(preset("Light ECM").group_id)
        );

        assert!(write_drone_groups(&path, &ids(&[]), "{dps}", false).is_err());

        // Two groups holding drones match Hobgoblin; the one already named
        // like the result is taken over and the other kept, so neither
        // overwrites the other
        let initial = json!({
            "bytes:ui": {
                "bytes:droneBlah2": {"tuple": ["long:1", {
                    "utf8:Federation Navy Hobgoblin": group("Federation Navy Hobgoblin", &["long:42"]),
                    "utf8:Hobgoblin": group("Hobgoblin", &["long:7"]),
                }]},
            }
        });
        fs::write(&path, encode_settings_json(&initial, false).unwrap()).unwrap();
        write_drone_groups(&path, &ids(&["hobgoblin"]), "{name}", false).unwrap();
        let (json, _) = load_settings_json(&path).unwrap();
        let groups = stored_groups(&json).unwrap();
        assert_eq!(groups.len(), 2);
        assert_eq!(
            groups["utf8:Hobgoblin"]["bytes:droneIDs"],
            json!(["long:7"])
        );
        assert_eq!(
            groups["utf8:Federation Navy Hobgoblin"]["bytes:droneIDs"],
            json!(["long:42"])
        );

        fs::remove_dir_all(&dir).ok();
    }
}
