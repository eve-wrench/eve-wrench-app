// Dialogs the player ticked "don't show again" on live in the account
// (core_user) file under suppress -> "suppress.<DialogKey>" as (timestamp,
// button). The client hands the stored button back to whatever asked, so a
// suppressed dialog only works when it is the button that caller checks for:
// Yes for Yes/No dialogs, OK for OK/Cancel ones. The catalog knows it for most
// dialogs; the rest can only be un-suppressed.

use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::Path;
use std::sync::Arc;

use serde::Deserialize;
use serde_json::{Map, Value, json};

use crate::backups::auto_backup;
use crate::catalog::RemoteCatalog;
use crate::marshal::{encode_settings_json, filetime_now, load_settings_json, strip_type_prefix};

const SUPPRESS_KEY: &str = "bytes:suppress";
const PREFIX: &str = "suppress.";

// Generated by tools/dialog-catalog from the client's dialog definitions,
// localization and code.
static CATALOG: RemoteCatalog<Confirmation> = RemoteCatalog::new(
    "confirmation catalog",
    include_str!("../data/confirmations.json"),
    "confirmations.json",
    1,
    "client_build",
    "dialogs",
);

#[derive(Deserialize, Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[serde(rename_all = "lowercase")]
pub enum ConfirmationKind {
    Question,
    Warning,
    Notice,
    // Feature introduction pages
    Welcome,
}

#[derive(Deserialize, Debug, Clone)]
pub struct Confirmation {
    pub key: String,
    pub kind: ConfirmationKind,
    // Button stored when suppressing; None when it isn't known
    pub answer: Option<u8>,
    title: HashMap<String, String>,
    #[serde(default)]
    body: HashMap<String, String>,
}

impl Confirmation {
    // Texts in "en" or "zh", falling back to English.
    pub fn title(&self, language: &str) -> &str {
        localized(&self.title, language).unwrap_or(&self.key)
    }

    pub fn body(&self, language: &str) -> Option<&str> {
        localized(&self.body, language)
    }

    pub fn can_suppress(&self) -> bool {
        self.answer.is_some()
    }
}

fn localized<'a>(texts: &'a HashMap<String, String>, language: &str) -> Option<&'a str> {
    texts
        .get(language)
        .or_else(|| texts.get("en"))
        .map(String::as_str)
}

// Sorted by dialog key.
pub fn catalog() -> Arc<[Confirmation]> {
    CATALOG.items()
}

pub fn load_cached_catalog(data_dir: &Path) {
    CATALOG.load_cached(data_dir);
}

// CI regenerates the catalog after each client build that changes dialogs.
pub fn refresh_catalog(data_dir: &Path) -> Result<bool, String> {
    CATALOG.refresh(data_dir)
}

fn stored(root: &Value) -> Option<&Map<String, Value>> {
    root.get(SUPPRESS_KEY).and_then(Value::as_object)
}

fn dialog_key(stored_key: &str) -> Option<&str> {
    strip_type_prefix(stored_key).strip_prefix(PREFIX)
}

// Some client code stores a plain `True` instead of a button.
fn is_suppressed(value: &Value) -> bool {
    let value = value.get("tuple").and_then(|t| t.get(1)).unwrap_or(value);
    !matches!(value, Value::Null | Value::Bool(false))
}

fn suppressed_in_settings(root: &Value) -> HashSet<String> {
    stored(root)
        .into_iter()
        .flatten()
        .filter(|(_, value)| is_suppressed(value))
        .filter_map(|(key, _)| dialog_key(key).map(str::to_string))
        .collect()
}

// Leaves dialogs that stay suppressed as they are, so their stored answer
// survives; anything newly suppressed needs a known answer.
fn suppressed_into_settings(
    root: &mut Value,
    catalog: &[Confirmation],
    suppressed: &HashSet<String>,
) -> Result<(), String> {
    let section = root
        .as_object_mut()
        .ok_or("Settings file has an unexpected structure")?
        .entry(SUPPRESS_KEY.to_string())
        .or_insert_with(|| json!({}))
        .as_object_mut()
        .ok_or("Settings 'suppress' section has an unexpected structure")?;

    section.retain(|key, value| {
        dialog_key(key).is_none_or(|dialog| suppressed.contains(dialog) && is_suppressed(value))
    });
    let present: HashSet<String> = section
        .keys()
        .filter_map(|key| dialog_key(key).map(str::to_string))
        .collect();

    let now = format!("long:{}", filetime_now());
    for key in suppressed.difference(&present) {
        let answer = catalog
            .iter()
            .find(|c| &c.key == key)
            .and_then(|c| c.answer)
            .ok_or_else(|| format!("The answer for dialog {key} is not known"))?;
        section.insert(
            format!("bytes:{PREFIX}{key}"),
            json!({"tuple": [now, answer]}),
        );
    }
    Ok(())
}

// Keys of the dialogs the account has suppressed, including ones the catalog
// doesn't know.
pub fn read_suppressed(path: &Path) -> Result<HashSet<String>, String> {
    let (json, _) = load_settings_json(path)?;
    Ok(suppressed_in_settings(&json))
}

pub fn write_suppressed(
    path: &Path,
    suppressed: &HashSet<String>,
    backup: bool,
) -> Result<(), String> {
    if !path.exists() {
        return Err("Settings file does not exist".into());
    }
    if backup {
        auto_backup(path, "pre-confirmations")?;
    }

    let (mut json, had_crc) = load_settings_json(path)?;
    suppressed_into_settings(&mut json, &catalog(), suppressed)?;
    let bytes = encode_settings_json(&json, had_crc)?;
    fs::write(path, bytes).map_err(|e| format!("Failed to write settings file: {}", e))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn keys(list: &[&str]) -> HashSet<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    fn settings() -> Value {
        json!({
            "bytes:suppress": {
                "bytes:suppress.AskQuitGame": {"tuple": ["long:1", 6]},
                "bytes:suppress.ConfirmPlugInImplant": {"tuple": ["long:1", 1]},
                "bytes:suppress.SomethingNew": {"tuple": ["long:1", 6]},
                "bytes:suppress.Cleared": {"tuple": ["long:1", false]},
                "bytes:unrelated": {"tuple": ["long:1", 3]},
            },
            "bytes:ui": {},
        })
    }

    #[test]
    fn bundled_catalog_has_known_answers() {
        let catalog = catalog();
        let answer = |key: &str| catalog.iter().find(|c| c.key == key).unwrap().answer;
        // Matches what the client stores when the player ticks the box
        assert_eq!(answer("AskQuitGame"), Some(6));
        assert_eq!(answer("ConfirmPlugInImplant"), Some(1));
        assert_eq!(answer("JumpCheckIntoStructure"), Some(6));
        assert_eq!(answer("ConfirmJumpToUnsafeSS"), Some(1));
    }

    #[test]
    fn reads_suppressed_dialogs() {
        assert_eq!(
            suppressed_in_settings(&settings()),
            keys(&["AskQuitGame", "ConfirmPlugInImplant", "SomethingNew"])
        );
        assert!(suppressed_in_settings(&json!({})).is_empty());
    }

    #[test]
    fn writes_only_what_changed() {
        let mut root = settings();
        let wanted = keys(&[
            "ConfirmPlugInImplant",
            "PutOffline",
            "ConfirmJumpToUnsafeSS",
        ]);
        suppressed_into_settings(&mut root, &catalog(), &wanted).unwrap();

        let section = root[SUPPRESS_KEY].as_object().unwrap();
        // Kept with its original timestamp
        assert_eq!(
            section["bytes:suppress.ConfirmPlugInImplant"],
            json!({"tuple": ["long:1", 1]})
        );
        assert_eq!(section["bytes:suppress.PutOffline"]["tuple"][1], json!(6));
        assert_eq!(
            section["bytes:suppress.ConfirmJumpToUnsafeSS"]["tuple"][1],
            json!(1)
        );
        // Cleared ones go, other settings in the section stay
        assert!(!section.contains_key("bytes:suppress.AskQuitGame"));
        assert!(!section.contains_key("bytes:suppress.SomethingNew"));
        assert!(!section.contains_key("bytes:suppress.Cleared"));
        assert!(section.contains_key("bytes:unrelated"));
        assert_eq!(suppressed_in_settings(&root), wanted);
    }

    #[test]
    fn refuses_dialogs_without_a_known_answer() {
        let unknown = catalog()
            .iter()
            .find(|c| c.answer.is_none())
            .unwrap()
            .key
            .clone();
        let mut root = settings();
        assert!(suppressed_into_settings(&mut root, &catalog(), &keys(&[&unknown])).is_err());
    }

    #[test]
    fn round_trips_through_marshal() {
        let dir = std::env::temp_dir().join("eve-wrench-confirmations-test");
        fs::create_dir_all(&dir).unwrap();
        let path = dir.join("core_user_12345.dat");
        fs::write(&path, encode_settings_json(&settings(), false).unwrap()).unwrap();

        write_suppressed(&path, &keys(&["AskQuitGame", "PutOffline"]), false).unwrap();
        assert_eq!(
            read_suppressed(&path).unwrap(),
            keys(&["AskQuitGame", "PutOffline"])
        );

        fs::remove_dir_all(&dir).ok();
    }
}
